_COMPILED = [(re.compile(r.pattern, re.IGNORECASE), r) for r in RULES]
_AND_SPLIT = re.compile(r"\b(?:а также|и)\s+(?:долж(?:ен|на|но|ны)\w*|\w+(?:ать|ять|ить|еть|ться)|обеспечива\w*|позволя\w*|отправля\w*|формиру\w*|сохраня\w*|выполня\w*)\b", re.IGNORECASE)
_NUMBER_RE = re.compile(r"\d")


@dataclass
class RuleHit:
    req_id: str
    criterion: str
    severity: str
    quote: str
    term: str
    problem: str
    fix: str
    terms: list | None = None
    terms_label: str = ""


def check_requirement(req: Requirement) -> list[RuleHit]:
    text = req.text
    hits: list[RuleHit] = []
    for rx, rule in _COMPILED:
        ms = []
        seen: set[str] = set()
        for m in rx.finditer(text):
            if rule.skip_if_number_near and _NUMBER_RE.search(text[max(0, m.start() - 30): m.end() + 60]):
                continue
            if m.group(0).lower() in seen:
                continue
            seen.add(m.group(0).lower())
            ms.append(m)
        if not ms:
            continue
        # одно замечание на правило: цитата охватывает все найденные маркеры
        terms = ", ".join(f"«{m.group(0)}»" for m in ms)
        hits.append(RuleHit(req.rid, rule.criterion, rule.severity, _context(text, ms[0].start(), ms[-1].end()),
                            ms[0].group(0), rule.problem, rule.fix))
        hits[-1].terms = [m.group(0) for m in ms]
        hits[-1].terms_label = terms
    # несколько требований в одном (единичность)
    if _AND_SPLIT.search(text) or text.count(";") >= 2:
        m = _AND_SPLIT.search(text)
        q = _context(text, m.start(), m.end()) if m else text[:120]
        hits.append(RuleHit(req.rid, "singular", "minor", q, m.group(0) if m else ";",
                            "Похоже, в одной формулировке объединено несколько требований.",
                            "Разделить на отдельные требования с собственными идентификаторами."))
    return hits


def _context(text: str, start: int, end: int, width: int = 45) -> str:
    """Цитата вокруг совпадения — по границам слов, дословно из текста."""
    s = max(0, start - width)
    e = min(len(text), end + width)
    if s > 0:
        sp = text.find(" ", s)
        s = sp + 1 if 0 <= sp < start else s
    if e < len(text):
        sp = text.rfind(" ", end, e)
        e = sp if sp > end else e
    return text[s:e].strip()
