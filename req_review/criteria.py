def criterion_name(key: str) -> str:
    if key in INDIVIDUAL:
        return INDIVIDUAL[key][0]
    if key in SET:
        return SET[key][0]
    return key


def criterion_ref(key: str) -> str:
    if key in INDIVIDUAL:
        return INDIVIDUAL[key][1]
    if key in SET:
        return SET[key][1]
    return ""


def criteria_prompt_block(which: dict) -> str:
    return "\n".join(f"- {k}: {v[0]} ({v[1]}). {v[2]}" for k, v in which.items())
