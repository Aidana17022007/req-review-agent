"""v14: нечёткое сопоставление ответов с вопросами нового прогона (выдуманный пример, не документ организаторов)."""
from types import SimpleNamespace as NS

from req_review.answers import _resolve, match_score, parse_answers

# вопросы «нового прогона»: номера S-xx сдвинулись, у одного замечания набора добавилось требование,
# к R-011 два разных вопроса с одной и той же меткой (R-011, complete)
QS = [
    NS(qid="Q-01", rid="S-01", ref="S-01", criterion="set_consistent", refs=["R-014", "R-013"],
       text="Непротиворечивость (R-013, R-014): метод объявлен как GET, но выполняет сохранение порога — изменение данных."),
    NS(qid="Q-02", rid="S-03", ref="S-03", criterion="set_complete", refs=["R-006", "R-007", "R-008"],
       text="Полнота набора: не описан контракт события внешней системы — состав полей, типы операций, дедупликация."),
    NS(qid="Q-03", rid="R-011", ref="R-011", criterion="complete", refs=[],
       text="Не определено, к какому месяцу относится покупка, совершённая на стыке месяцев (23:59 последнего дня)."),
    NS(qid="Q-04", rid="R-011", ref="R-011", criterion="complete", refs=[],
       text="В примере не заданы исходные условия: состояние переключателя уведомлений и значение счётчика на начало."),
    NS(qid="Q-05", rid="R-020", ref="R-020", criterion="verifiable", refs=[],
       text="Срок доставки push не задан числом и перцентилем — требование нельзя проверить тестом."),
]

TEMPLATE = """# Ответы аналитика — выдуманный пример

### Q-07. S-05 — Набор требований

<!-- reqlens: S-05 set_consistent R-013,R-014 -->
**Вопрос.** Непротиворечивость (R-014, R-013): метод объявлен как GET, но выполняет изменение данных («Сохранение»).

Ответ: Сохранение — методом PUT /alerts/limit, GET только для чтения.

### Q-04. S-04 — Набор требований

<!-- reqlens: S-04 set_complete R-006,R-008 -->
**Вопрос.** Полнота набора (R-006, R-008): контракт события внешней системы не описан — нет состава полей и типов операций.

Ответ: Контракт события согласуем позже.

### Q-51. R-011 — Функциональные

<!-- reqlens: R-011 complete -->
**Вопрос.** Не заданы исходные условия примера: состояние переключателя и счётчик на начало месяца.

Ответ: Переключатель включён, счётчик 0 ₸, покупка 4 000 ₸.

### Q-42. R-011 — Функциональные

<!-- reqlens: R-011 complete -->
**Вопрос.** К какому месяцу относится покупка на стыке месяцев?

Ответ: Месяц определяется по дате совершения покупки.

### Q-60. R-099 — Функциональные

<!-- reqlens: R-099 complete -->
**Вопрос.** Не описан формат выгрузки отчёта для регулятора.

Ответ: CSV, разделитель «;».

### Q-61. S-09 — Набор требований

<!-- reqlens: S-09 set_consistent R-013,R-014 -->
**Вопрос.** Лимит в 500 000 тенге в одном пункте и 300 000 тенге в другом — какое значение верное?

Ответ: 300 000 тенге.
"""


def test_fuzzy_matching_finds_shifted_questions_and_keeps_unknown_honest():
    parsed = parse_answers(TEMPLATE)
    assert parsed["Q-42"]["question"].startswith("К какому месяцу")  # текст вопроса из шаблона сохраняется
    pairs, unknown = _resolve(QS, parsed)
    got = {m.src: (m[0].qid, m.how) for m in pairs}
    assert got["Q-07"] == ("Q-01", "метка")  # S-05 → S-01: то же множество требований, порядок другой
    assert got["Q-04"] == ("Q-02", "похожий вопрос")  # S-04 → S-03: добавилось R-007, текст похож
    assert got["Q-51"] == ("Q-04", "метка") and got["Q-42"] == ("Q-03", "метка")  # одна метка — решает текст вопроса
    # R-099 нет в прогоне; S-09 — те же требования, что у S-01, но вопрос о другом (лимиты), а S-01 уже занят
    assert unknown == ["Q-60", "Q-61"]


def test_match_score_requires_shared_requirements_and_related_criterion():
    q = QS[1]
    assert match_score(("S-04", "set_complete", "R-006,R-008"), "контракт события внешней системы не описан", q)[0] >= 0.5
    assert match_score(("R-030", "set_complete", ""), "контракт события внешней системы не описан", q) == (0.0, "")
    assert match_score(("S-04", "singular", "R-006,R-008"), "контракт события внешней системы не описан", q) == (0.0, "")
    # без текста вопроса (старый файл ответов) похожий вопрос принимается только при сильном совпадении
    assert match_score(("S-04", "set_complete", "R-006"), "", q)[0] < 0.5
